export function HelpButton({ className }: { className?: string }) {
  const [open, setOpen] = useState(false);
  const [tab, setTab] = useState(SECTIONS[0]!.id);
  const current = SECTIONS.find((s) => s.id === tab) ?? SECTIONS[0]!;

  return (
    <>
      <Button
        variant="ghost"
        size="icon-sm"
        className={cn(className)}
        aria-label="راهنما"
        onClick={() => setOpen(true)}
      >
        <BookOpen className="size-4" />
      </Button>
      <Dialog open={open} onOpenChange={setOpen}>
        <DialogContent className="max-w-lg max-h-[85vh] overflow-hidden flex flex-col">
          <DialogTitle className="text-base font-semibold shrink-0">راهنمای سیباموتور</DialogTitle>
          <p className="mt-1 text-[12px] text-muted shrink-0">
            خلاصه کار با تخته، چت، گزارش‌ها، اعلان‌ها و حساب کاربری
          </p>
          <div className="mt-3 flex flex-wrap gap-1 shrink-0">
            {SECTIONS.map((s) => (
              <button
                key={s.id}
                type="button"
                onClick={() => setTab(s.id)}
                className={cn(
                  "rounded-full px-3 py-1 text-[12px]",
                  tab === s.id ? "bg-accent text-accent-fg" : "bg-surface-2 text-muted hover:text-fg",
                )}
              >
                {s.title}
              </button>
            ))}
          </div>
          <ul className="mt-4 space-y-2.5 overflow-y-auto text-[13px] leading-relaxed text-muted min-h-0 flex-1 pe-1">
            {current.items.map((item) => (
              <li key={item} className="flex gap-2">
                <span className="mt-1.5 size-1.5 shrink-0 rounded-full bg-accent" />
                <span>{item}</span>
              </li>
            ))}
          </ul>
          <Button className="mt-4 w-full shrink-0" variant="secondary" onClick={() => setOpen(false)}>
            بستن
          </Button>
        </DialogContent>
      </Dialog>
    </>
  );
}
